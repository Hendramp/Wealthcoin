alter table public.marketplace_listings
  add column if not exists escrow_address text,
  add column if not exists buyer_address text,
  add column if not exists tx_hash text,
  add column if not exists sold_at timestamptz,
  add column if not exists status_chain text;

create index if not exists marketplace_listings_escrow_address_idx
  on public.marketplace_listings (escrow_address);

alter table public.hub_profiles
  add column if not exists wallet_address text;

create table if not exists public.escrow_disputes (
  id bigint generated by default as identity primary key,
  escrow_address text not null,
  reason text not null,
  raised_by text,
  created_at timestamptz not null default now()
);

create index if not exists escrow_disputes_escrow_address_idx
  on public.escrow_disputes (escrow_address);

alter table public.escrow_disputes enable row level security;

drop policy if exists "party can raise dispute reason" on public.escrow_disputes;
create policy "party can raise dispute reason"
  on public.escrow_disputes
  for insert
  to authenticated
  with check (auth.uid() is not null);

drop policy if exists "authenticated can read dispute reasons" on public.escrow_disputes;
create policy "authenticated can read dispute reasons"
  on public.escrow_disputes
  for select
  to authenticated
  using (auth.uid() is not null);

alter table public.marketplace_listings enable row level security;

drop policy if exists "buyers can fund marketplace escrow fields" on public.marketplace_listings;
create policy "buyers can fund marketplace escrow fields"
  on public.marketplace_listings
  for update
  to authenticated
  using (
    status = 'active'
    or user_id = auth.uid()
  )
  with check (
    status = 'active'
    or user_id = auth.uid()
  );

drop policy if exists "sellers can read escrow sale fields" on public.marketplace_listings;
create policy "sellers can read escrow sale fields"
  on public.marketplace_listings
  for select
  to authenticated
  using (
    user_id = auth.uid()
    or status = 'active'
  );
